import { adminRefreshAccessToken } from "./refreshAccessToken";
const adminAddCoupon = async (couponCode, couponAmount, fromDate, toDate) => {
  try {
    const fetchMethod = async (accessToken) => {
      const response = await fetch(
        `${process.env.NEXT_PUBLIC_BACKEND_BASE_URL}/api/admin/coupon`,
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${accessToken}`
          },
          body: JSON.stringify({
            couponCode,
            couponAmount: Number(couponAmount),
            toDate,
            fromDate
          })
        }
      );

      return response;
    };

    return await adminRefreshAccessToken(fetchMethod);
  } catch (error) {
    return { ok: false, json: { error: error.message } };
  }
};

export default adminAddCoupon;
